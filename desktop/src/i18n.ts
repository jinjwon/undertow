export const STRINGS: Record<Lang, Record<Key, string>> = { en, ko, ja }

export const langFrom = (system: string | undefined): Lang => {
  const base = (system ?? '').slice(0, 2).toLowerCase()
  return base === 'ko' || base === 'ja' ? base : 'en'
}

export const tr = (lang: Lang, key: Key, vars: Record<string, string | number> = {}) =>
  STRINGS[lang][key].replace(/\{(\w+)\}/g, (all, name) => (name in vars ? String(vars[name]) : all))
